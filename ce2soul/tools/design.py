#!/usr/bin/env python3
"""Generate circuit-derived float32 filter coefficients; requires numpy/scipy."""
from pathlib import Path
import json, math
import numpy as np
from scipy.signal import bilinear
ROOT=Path(__file__).resolve().parents[1]
FS=44100
R=1e4;c6=3.3e-9;c7=8.2e-9;c8=470e-12
# Ideal unity emitter follower, high input impedance; nodal KCL, no transistor loading.
lp=[R**3*c6*c7*c8,2*R**2*c8*(c6+c7),R*(c6+3*c8),1]
pre_b=[57000*6.8e-9,1]
pre_a=np.polymul([10000*6.8e-9,1],[47000*100e-12,1]).tolist()
de_b=[10000*6.8e-9,1]
de_a=[10000*47000*6.8e-9*100e-12,57000*6.8e-9+47000*100e-12,1]
models={'PRE':(pre_b,pre_a),'POST':(de_b,de_a),'LP':([1],lp),
 'HP_PRE':([100000*33e-9,0],[100000*33e-9,1]),
 'HP_POST':([330000*33e-9,0],[330000*33e-9,1]),
 'HP_WET':([1e6*33e-9,0],[1e6*33e-9,1])}
lines=['/* Generated by tools/design.py: 44.1 kHz bilinear, no prewarp. */']
report={}
for name,(b,a) in models.items():
 bz,az=bilinear(b,a,fs=FS);bz=np.asarray(bz,dtype=np.float32);az=np.asarray(az,dtype=np.float32)
 report[name]={'analog_b':list(b),'analog_a':list(a),'b':bz.astype(float).tolist(),'a':az.astype(float).tolist()}
 def fmt(v):
  t=format(float(v),'.9g');return t+('f' if '.' in t or 'e' in t else '.0f')
 lines += [f'static const float CE_{name}_B[{len(bz)}]={{'+','.join(map(fmt,bz))+'};',f'static const float CE_{name}_A[{len(az)}]={{'+','.join(map(fmt,az))+'};']
# Rate divider model: R31/(R31+remaining VR1), max f from R30/(4*C19*R29*R32).
fmax=47000/(4*.1e-6*33000*1e6)
rate=[fmax*10000/(10000+100000*(1-i/100)) for i in range(101)]
lines+=['static const float CE_RATE[101]={'+','.join(format(x,'.9g')+'f' for x in rate)+'};',f'#define CE_LFO_RC {1-math.exp(-1/(FS*220000*.01e-6)):.9g}f',f'#define CE_CONTROL_SLEW {1-math.exp(-1/(FS*.02)):.9g}f']
(ROOT/'src/coefficients.h').write_text('\n'.join(lines)+'\n')
(ROOT/'docs/design.json').write_text(json.dumps({'sample_rate':FS,'filters':report,'rate_hz':rate,'delay_ms':[8.5,10.75],'delay_range_status':'provisional, published circuit analysis comment; NOT hardware measurement'},indent=2)+'\n')
