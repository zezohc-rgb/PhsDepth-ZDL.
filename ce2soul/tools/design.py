#!/usr/bin/env python3
"""Generate circuit-derived float32 SOS filters and loaded LFO control law."""
from pathlib import Path
import json, math
import numpy as np
from scipy.signal import bilinear,tf2sos
from delay_model import fit
ROOT=Path(__file__).resolve().parents[1];FS=44100
R=1e4;c6=3.3e-9;c7=8.2e-9;c8=470e-12
# Exact four-node small-signal circuit with ideal unity emitter follower.
# Input coupling C0, shunt R0 and lowpass are solved together, not cascaded.
def coupled_lp(R0,C0=33e-9):
 a=[C0*c6*c7*c8*R**3*R0,
    2*C0*c8*R**2*R0*(c6+c7)+c6*c7*c8*R**3+c6*c7*c8*R**2*R0,
    C0*R*R0*(c6+3*c8)+2*c6*c8*R**2+2*c6*c8*R*R0+2*c7*c8*R**2+c7*c8*R*R0,
    C0*R0+c6*(R+R0)+c8*(3*R+R0),1]
 return [C0*R0,0],a
# C2 is in series with R4 || (R5+C3), and C4 shunts R6.
pre_b=np.polymul([47000*.47e-6,0],[57000*6.8e-9,1]).tolist()
pre_a=np.polymul([47000*100e-12,1],[47000*10000*.47e-6*6.8e-9,57000*6.8e-9+47000*.47e-6,1]).tolist()
de_b=[10000*6.8e-9,1];de_a=[10000*47000*6.8e-9*100e-12,57000*6.8e-9+47000*100e-12,1]
# R22 terminates at op-amp virtual reference: it loads C14 with R20.
wet_r=1/(1/1e6+1/47000)
models={'PRE':(pre_b,pre_a),'POST':(de_b,de_a),
 'BBD_IN':coupled_lp(100000),'BBD_OUT':coupled_lp(330000),
 'HP_WET':([wet_r*33e-9,0],[wet_r*33e-9,1])}
lines=['/* Generated by tools/design.py: 44.1 kHz BLT, ideal follower, float32 SOS. */'];report={}
def fmt(v):
 t=format(float(v),'.9g');return t+('f' if '.' in t or 'e' in t else '.0f')
for name,(b,a) in models.items():
 bz,az=bilinear(b,a,fs=FS);sos=np.asarray(tf2sos(bz,az),dtype=np.float32)
 report[name]={'analog_b':list(b),'analog_a':list(a),'sos':sos.astype(float).tolist()}
 rows=[row[[0,1,2,4,5]] for row in sos]
 lines += [f'static const float CE_{name}[{len(sos)}][5]={{'+','.join('{'+','.join(map(fmt,row))+'}' for row in rows)+'};']
fmax=47000/(4*.1e-6*33000*1e6)
rate=[];lfo_alpha=[]
for i in range(101):
 x=i/100;top=(1-x)*1e5;bottom=1e4+x*1e5
 # Loaded wiper: integrator R32=1M ends at virtual reference.
 rate.append(fmax*bottom/(top+bottom+top*bottom/1e6))
 # DEPTH pot Thevenin resistance is in series with R35.
 rt=x*(1-x)*1e5
 lfo_alpha.append(1-math.exp(-1/(FS*(220000+rt)*10e-9)))
for name,values in [('RATE',rate),('LFO_ALPHA',lfo_alpha)]:
 lines+=['static const float CE_'+name+'[101]={'+','.join(map(fmt,values))+'};']
delay=fit()
lines += [f'#define CE_DELAY_CENTER {fmt(delay["center_samples"])}',f'#define CE_DELAY_AMPLITUDE {fmt(delay["amplitude_samples"])}']
lines += [f'#define CE_CONTROL_SLEW {1-math.exp(-1/(FS*.02)):.9g}f']
(ROOT/'src/coefficients.h').write_text('\n'.join(lines)+'\n')
(ROOT/'docs/design.json').write_text(json.dumps({'sample_rate':FS,'filters':report,'rate_hz':rate,'lfo_alpha':lfo_alpha,'wet_coupling_hz':1/(2*math.pi*wet_r*33e-9),'delay_ms':delay['full_depth_delay_ms_extrapolated'],'delay_model':delay},indent=2)+'\n')
